// Package deprecation tells users about deprecated resources: as an admission warning when
// they apply one, and as an event plus a log line at every operator startup.
package deprecation

import (
	"context"

	"github.com/gravitee-io/gravitee-kubernetes-operator/api/v1alpha1"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/core"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/env"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/k8s"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/log"
	corev1 "k8s.io/api/core/v1"
	netV1 "k8s.io/api/networking/v1"
	"k8s.io/client-go/tools/record"
	"sigs.k8s.io/controller-runtime/pkg/client"
)

const (
	ApiV2Notice = "ApiDefinition (v2 API) is deprecated and will be removed in October 2027, " +
		"please migrate to ApiV4Definition."

	// IngressNotice is also written in helm/gko/templates/NOTES.txt and helm/gko/values.yaml.
	IngressNotice = "The Gravitee Ingress controller is deprecated: it generates v2 APIs, " +
		"which will be removed in October 2027. Please migrate to the Gateway API (HTTPRoute), " +
		"enabled with the Helm value gatewayAPI.controller.enabled=true."

	// Reason is the reason of the Warning events recorded on deprecated resources.
	Reason = "Deprecated"
)

// ApiDefinitionNotice returns the notice for a v2 API: the Ingress one for an Ingress
// template, whose users must leave the Ingress controller rather than move the template to
// ApiV4Definition, and "" for an API generated by the Ingress controller, which only the
// operator would see.
func ApiDefinitionNotice(api *v1alpha1.ApiDefinition) string {
	switch {
	case api.GetAnnotations()[core.Extends] == core.IngressLabel:
		return ""
	case api.GetAnnotations()[core.IngressTemplateAnnotation] == env.TrueString:
		return IngressNotice
	default:
		return ApiV2Notice
	}
}

// StartupNotice records a Warning event on every deprecated resource and logs it, each time
// the operator starts. An admission warning only reaches whoever applies a resource, so
// resources applied before an upgrade would otherwise never show it.
// It is a manager runnable: it runs on the leader, once the caches have synced.
type StartupNotice struct {
	Client   client.Client
	Recorder record.EventRecorder
	// Ingresses is true when the Ingress controller is enabled: Gravitee Ingresses are notified too.
	Ingresses bool
}

func (n StartupNotice) Start(ctx context.Context) error {
	apis := &v1alpha1.ApiDefinitionList{}
	if err := n.Client.List(ctx, apis); err != nil {
		log.Error(ctx, err, "Unable to list v2 APIs for the deprecation notice")
		return nil
	}
	for i := range apis.Items {
		n.notify(ctx, &apis.Items[i], "ApiDefinition", ApiDefinitionNotice(&apis.Items[i]))
	}
	if n.Ingresses {
		n.notifyIngresses(ctx)
	}
	return nil
}

func (n StartupNotice) notifyIngresses(ctx context.Context) {
	ingresses := &netV1.IngressList{}
	if err := n.Client.List(ctx, ingresses); err != nil {
		log.Error(ctx, err, "Unable to list Ingresses for the deprecation notice")
		return
	}
	for i := range ingresses.Items {
		if k8s.IsGraviteeIngress(&ingresses.Items[i]) {
			n.notify(ctx, &ingresses.Items[i], "Ingress", IngressNotice)
		}
	}
}

func (n StartupNotice) notify(ctx context.Context, obj client.Object, kind, notice string) {
	if notice == "" || !obj.GetDeletionTimestamp().IsZero() {
		return
	}
	n.Recorder.Event(obj, corev1.EventTypeWarning, Reason, notice)
	log.Info(ctx, notice,
		"kind", kind,
		"namespace", obj.GetNamespace(),
		"name", obj.GetName(),
		"severity", "warning",
	)
}
