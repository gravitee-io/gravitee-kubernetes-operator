package deprecation_test

import (
	"context"

	"github.com/gravitee-io/gravitee-kubernetes-operator/api/v1alpha1"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/core"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/deprecation"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	netV1 "k8s.io/api/networking/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/client-go/tools/record"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/client/fake"
)

var _ = Describe("Startup notice", func() {
	ctx := context.Background()

	runWith := func(ingresses bool, objects ...client.Object) []string {
		scheme := runtime.NewScheme()
		Expect(v1alpha1.AddToScheme(scheme)).To(Succeed())
		Expect(netV1.AddToScheme(scheme)).To(Succeed())
		recorder := record.NewFakeRecorder(len(objects) + 1)

		notice := deprecation.StartupNotice{
			Client:    fake.NewClientBuilder().WithScheme(scheme).WithObjects(objects...).Build(),
			Recorder:  recorder,
			Ingresses: ingresses,
		}
		Expect(notice.Start(ctx)).To(Succeed())

		close(recorder.Events)
		events := []string{}
		for e := range recorder.Events {
			events = append(events, e)
		}
		return events
	}
	run := func(objects ...client.Object) []string { return runWith(true, objects...) }
	warning := func(notice string) string { return "Warning " + deprecation.Reason + " " + notice }

	ingress := func(class string) *netV1.Ingress {
		return &netV1.Ingress{
			ObjectMeta: metav1.ObjectMeta{Name: class + "-ingress", Namespace: "default"},
			Spec:       netV1.IngressSpec{IngressClassName: &class},
		}
	}

	apiDefinition := func(name string, annotations map[string]string) *v1alpha1.ApiDefinition {
		return &v1alpha1.ApiDefinition{
			ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: "default", Annotations: annotations},
		}
	}

	It("records a warning event on a v2 API", func() {
		events := run(apiDefinition("user-api", nil))

		Expect(events).To(ConsistOf(warning(deprecation.ApiV2Notice)))
	})

	It("records nothing on a v2 API generated by the Ingress controller", func() {
		events := run(apiDefinition("generated", map[string]string{core.Extends: core.IngressLabel}))

		Expect(events).To(BeEmpty())
	})

	It("records the Ingress notice on an Ingress template", func() {
		events := run(apiDefinition("template", map[string]string{core.IngressTemplateAnnotation: "true"}))

		Expect(events).To(ConsistOf(warning(deprecation.IngressNotice)))
	})

	It("records the Ingress notice on a Gravitee Ingress only", func() {
		events := run(ingress("graviteeio"), ingress("nginx"))

		Expect(events).To(ConsistOf(warning(deprecation.IngressNotice)))
	})

	It("records nothing on Ingresses when the Ingress controller is disabled", func() {
		events := runWith(false, ingress("graviteeio"))

		Expect(events).To(BeEmpty())
	})
})
