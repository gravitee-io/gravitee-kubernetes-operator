package apidefinition_test

import (
	"context"

	"github.com/gravitee-io/gravitee-kubernetes-operator/api/v1alpha1"
	v2 "github.com/gravitee-io/gravitee-kubernetes-operator/internal/admission/api/v2"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/core"
	"github.com/gravitee-io/gravitee-kubernetes-operator/internal/deprecation"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

var _ = Describe("v2 API deprecation warning", func() {
	ctx := context.Background()
	admissionCtrl := v2.AdmissionCtrl{}

	// An ingress template skips every check that needs a cluster or APIM.
	newTemplate := func() *v1alpha1.ApiDefinition {
		return &v1alpha1.ApiDefinition{
			ObjectMeta: metav1.ObjectMeta{
				Name:        "template",
				Namespace:   "default",
				Annotations: map[string]string{core.IngressTemplateAnnotation: "true"},
			},
		}
	}

	It("warns on create", func() {
		warnings, err := admissionCtrl.ValidateCreate(ctx, newTemplate())

		Expect(err).ToNot(HaveOccurred())
		Expect(warnings).To(ConsistOf(deprecation.ApiV2Notice))
	})

	It("does not warn on an API generated by the Ingress controller", func() {
		generated := &v1alpha1.ApiDefinition{
			ObjectMeta: metav1.ObjectMeta{
				Name:        "generated",
				Namespace:   "default",
				Annotations: map[string]string{core.Extends: core.IngressLabel},
			},
		}

		// The rest of the validation needs a cluster; the warning is decided before it.
		warnings, _ := admissionCtrl.ValidateCreate(ctx, generated)

		Expect(warnings).ToNot(ContainElement(deprecation.ApiV2Notice))
	})
})
